-- =====================================================================
-- PRYWATNE LISTY PRACOWNIKÓW (filtr "Lista" w Rozliczeniu czasu)
--
-- employee_lists         - lista: nazwa + właściciel (users.id)
-- employee_list_members  - pracownicy na liście
--
-- Każdy użytkownik widzi i zmienia WYŁĄCZNIE swoje listy (także administrator).
-- Usunięcie użytkownika usuwa jego listy; usunięcie pracownika usuwa go z list.
--
-- Wymaga wcześniejszego 01_przygotowanie.sql (funkcja app_user_id). Można uruchomić ponownie.
-- Uruchom w Supabase: SQL Editor -> wklej całość -> Run.
-- =====================================================================

begin;

create table if not exists public.employee_lists (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null default public.app_user_id()
             references public.users (id) on delete cascade,
  name       text not null check (length(btrim(name)) between 1 and 60),
  created_at timestamptz not null default now()
);

-- ta sama nazwa tylko raz u jednego użytkownika (bez względu na wielkość liter)
create unique index if not exists employee_lists_user_name_idx
  on public.employee_lists (user_id, lower(btrim(name)));

create table if not exists public.employee_list_members (
  list_id     bigint not null references public.employee_lists (id) on delete cascade,
  employee_id bigint not null references public.employees (id) on delete cascade,
  primary key (list_id, employee_id)
);

create index if not exists employee_list_members_emp_idx on public.employee_list_members (employee_id);

alter table public.employee_lists enable row level security;
alter table public.employee_list_members enable row level security;

revoke all on public.employee_lists, public.employee_list_members from anon;
grant select, insert, update, delete on public.employee_lists, public.employee_list_members to authenticated;

-- Listy: tylko własne
drop policy if exists employee_lists_own on public.employee_lists;
create policy employee_lists_own on public.employee_lists
  for all to authenticated
  using (user_id = (select public.app_user_id()))
  with check (user_id = (select public.app_user_id()));

-- Członkowie: tylko na własnych listach
drop policy if exists employee_list_members_own on public.employee_list_members;
create policy employee_list_members_own on public.employee_list_members
  for all to authenticated
  using (exists (
    select 1 from public.employee_lists l
    where l.id = list_id and l.user_id = (select public.app_user_id())))
  with check (exists (
    select 1 from public.employee_lists l
    where l.id = list_id and l.user_id = (select public.app_user_id())));

commit;

notify pgrst, 'reload schema';

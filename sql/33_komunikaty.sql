-- =====================================================================
-- KOMUNIKATY (moduł "Komunikaty")
--
-- announcements          - komunikat: temat, treść (proste formatowanie), ważność, okres,
--                          czy wymaga potwierdzenia, czy wysłać push
-- announcement_targets   - odbiorcy:
--                            all_users         - wszyscy użytkownicy systemu
--                            user_dept / user_role / user - użytkownicy z działu / z rolą / wybrani
--                            emp_dept / employee            - pracownicy z działu / wybrani
-- announcement_reads     - kto i kiedy przeczytał (i czy potwierdził)
--
-- Tworzą i zarządzają: użytkownicy z uprawnieniem "Komunikaty" (users.allow_messages).
-- Odbiorca widzi tylko komunikaty skierowane do niego (app_my_announcements).
-- Push: po dodaniu aktywnego komunikatu z włączonym push baza wywołuje funkcję absence-push
-- (ta sama co dla nieobecności, sql/31) z { announcement_id }.
--
-- Wymaga wcześniejszego 01, 02 i 31. Można uruchomić ponownie.
-- Uruchom w Supabase: SQL Editor -> wklej całość -> Run.
-- =====================================================================

begin;

alter table public.users add column if not exists allow_messages boolean not null default false;

create table if not exists public.announcements (
  id          bigint generated by default as identity primary key,
  title       text not null check (length(btrim(title)) between 1 and 120),
  body        text not null default '' check (length(body) <= 5000),
  priority    text not null default 'info' check (priority in ('info', 'important', 'urgent')),
  require_ack boolean not null default false,
  push        boolean not null default true,
  starts_at   timestamptz not null default now(),
  ends_at     timestamptz,
  closed_at   timestamptz,
  created_by  bigint default public.app_user_id() references public.users (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz,
  check (ends_at is null or ends_at > starts_at)
);

create table if not exists public.announcement_targets (
  id              bigint generated by default as identity primary key,
  announcement_id bigint not null references public.announcements (id) on delete cascade,
  kind            text not null check (kind in ('all_users', 'user_dept', 'user_role', 'user', 'emp_dept', 'employee')),
  ref_id          bigint,
  check ((kind = 'all_users') = (ref_id is null))
);
create index if not exists announcement_targets_ann_idx on public.announcement_targets (announcement_id);

create table if not exists public.announcement_reads (
  id              bigint generated by default as identity primary key,
  announcement_id bigint not null references public.announcements (id) on delete cascade,
  user_id         bigint references public.users (id) on delete cascade,
  employee_id     bigint references public.employees (id) on delete cascade,
  read_at         timestamptz not null default now(),
  acked           boolean not null default false,
  check ((user_id is null) <> (employee_id is null))
);
create unique index if not exists announcement_reads_user_idx on public.announcement_reads (announcement_id, user_id) where user_id is not null;
create unique index if not exists announcement_reads_emp_idx on public.announcement_reads (announcement_id, employee_id) where employee_id is not null;

alter table public.announcements enable row level security;
alter table public.announcement_targets enable row level security;
alter table public.announcement_reads enable row level security;
revoke all on public.announcements, public.announcement_targets, public.announcement_reads from anon;
revoke all on public.announcements, public.announcement_targets, public.announcement_reads from authenticated;
grant select, insert, update, delete on public.announcements, public.announcement_targets to authenticated;
grant select on public.announcement_reads to authenticated;

-- Autorzy (uprawnienie "Komunikaty") zarządzają wszystkim; odbiorcy czytają przez app_my_announcements
drop policy if exists announcements_manage on public.announcements;
create policy announcements_manage on public.announcements
  for all to authenticated
  using ((select public.app_perm('allow_messages')))
  with check ((select public.app_perm('allow_messages')));

drop policy if exists announcement_targets_manage on public.announcement_targets;
create policy announcement_targets_manage on public.announcement_targets
  for all to authenticated
  using ((select public.app_perm('allow_messages')))
  with check ((select public.app_perm('allow_messages')));

drop policy if exists announcement_reads_select on public.announcement_reads;
create policy announcement_reads_select on public.announcement_reads
  for select to authenticated
  using ((select public.app_perm('allow_messages'))
         or user_id = (select public.app_user_id())
         or employee_id = (select public.app_employee_id()));

-- ---------------------------------------------------------------------
-- Odbiorcy komunikatu: użytkownicy i pracownicy wynikający z celów
-- ---------------------------------------------------------------------
create or replace function public.app_announcement_user_ids(p_id bigint)
returns setof bigint
language sql
stable
security definer
set search_path = public
as $$
  select distinct u.id
  from public.users u
  join public.announcement_targets t on t.announcement_id = p_id
  where t.kind = 'all_users'
     or (t.kind = 'user' and t.ref_id = u.id)
     or (t.kind = 'user_dept' and t.ref_id = u.department_id)
     or (t.kind = 'user_role' and t.ref_id = u.role_id)
$$;

create or replace function public.app_announcement_employee_ids(p_id bigint)
returns setof bigint
language sql
stable
security definer
set search_path = public
as $$
  select distinct e.id
  from public.employees e
  join public.announcement_targets t on t.announcement_id = p_id
  where e.active is not false
    and ((t.kind = 'employee' and t.ref_id = e.id)
      or (t.kind = 'emp_dept' and t.ref_id = e.department_id))
$$;

revoke execute on function public.app_announcement_user_ids(bigint) from public, anon, authenticated;
revoke execute on function public.app_announcement_employee_ids(bigint) from public, anon, authenticated;
grant execute on function public.app_announcement_user_ids(bigint) to service_role;
grant execute on function public.app_announcement_employee_ids(bigint) to service_role;

-- Komunikaty zalogowanej osoby (użytkownika albo pracownika): aktywne + z ostatnich 60 dni
create or replace function public.app_my_announcements()
returns table (
  id bigint, title text, body text, priority text, require_ack boolean,
  starts_at timestamptz, ends_at timestamptz, created_at timestamptz, updated_at timestamptz,
  author text, active boolean, read_at timestamptz, acked boolean
)
language sql
stable
security definer
set search_path = public
as $$
  with me as (
    select public.app_user_id() as uid, public.app_employee_id() as eid
  )
  select a.id, a.title, a.body, a.priority, a.require_ack, a.starts_at, a.ends_at, a.created_at, a.updated_at,
         btrim(coalesce(au.name, '') || ' ' || coalesce(au.last_name, '')),
         (a.closed_at is null and a.starts_at <= now() and (a.ends_at is null or a.ends_at > now())),
         r.read_at, coalesce(r.acked, false)
  from public.announcements a
  cross join me
  left join public.users au on au.id = a.created_by
  left join public.announcement_reads r
    on r.announcement_id = a.id
   and ((me.uid is not null and r.user_id = me.uid) or (me.uid is null and r.employee_id = me.eid))
  where a.starts_at <= now()
    and a.starts_at > now() - interval '60 days'
    and (
      (me.uid is not null and me.uid in (select public.app_announcement_user_ids(a.id)))
      or (me.uid is null and me.eid is not null and me.eid in (select public.app_announcement_employee_ids(a.id)))
    )
  order by a.starts_at desc
$$;

grant execute on function public.app_my_announcements() to authenticated;
revoke execute on function public.app_my_announcements() from anon;

-- Oznaczenie jako przeczytany (p_ack = potwierdzenie "Przeczytałem")
create or replace function public.app_announcement_read(p_id bigint, p_ack boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid bigint := public.app_user_id();
  v_eid bigint := public.app_employee_id();
begin
  if v_uid is not null then
    if not exists (select 1 from public.app_announcement_user_ids(p_id) x where x = v_uid) then
      raise exception 'Ten komunikat nie jest skierowany do Ciebie.';
    end if;
    insert into public.announcement_reads (announcement_id, user_id, acked)
    values (p_id, v_uid, coalesce(p_ack, false))
    on conflict (announcement_id, user_id) where user_id is not null
    do update set acked = public.announcement_reads.acked or excluded.acked;
  elsif v_eid is not null then
    if not exists (select 1 from public.app_announcement_employee_ids(p_id) x where x = v_eid) then
      raise exception 'Ten komunikat nie jest skierowany do Ciebie.';
    end if;
    insert into public.announcement_reads (announcement_id, employee_id, acked)
    values (p_id, v_eid, coalesce(p_ack, false))
    on conflict (announcement_id, employee_id) where employee_id is not null
    do update set acked = public.announcement_reads.acked or excluded.acked;
  else
    raise exception 'Brak zalogowanego konta.';
  end if;
end $$;

grant execute on function public.app_announcement_read(bigint, boolean) to authenticated;
revoke execute on function public.app_announcement_read(bigint, boolean) from anon;

-- Dla autora: lista odbiorców z informacją o odczycie
create or replace function public.app_announcement_recipients(p_id bigint)
returns table (kind text, person_id bigint, name text, department text, read_at timestamptz, acked boolean)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.app_perm('allow_messages') then
    raise exception 'Brak uprawnień do komunikatów.';
  end if;
  return query
    select 'user'::text, u.id, btrim(coalesce(u.name, '') || ' ' || coalesce(u.last_name, '')), d.department, r.read_at, coalesce(r.acked, false)
    from public.app_announcement_user_ids(p_id) x
    join public.users u on u.id = x
    left join public.department d on d.id = u.department_id
    left join public.announcement_reads r on r.announcement_id = p_id and r.user_id = u.id
    union all
    select 'employee'::text, e.id, btrim(coalesce(e.first_name, '') || ' ' || coalesce(e.last_name, '')), d.department, r.read_at, coalesce(r.acked, false)
    from public.app_announcement_employee_ids(p_id) x
    join public.employees e on e.id = x
    left join public.department d on d.id = e.department_id
    left join public.announcement_reads r on r.announcement_id = p_id and r.employee_id = e.id
    order by 1, 3;
end $$;

grant execute on function public.app_announcement_recipients(bigint) to authenticated;
revoke execute on function public.app_announcement_recipients(bigint) from anon;

-- ---------------------------------------------------------------------
-- Push przy wysłaniu komunikatu (gdy cele są już zapisane: strona wywołuje app_announcement_publish)
-- ---------------------------------------------------------------------
create or replace function public.app_announcement_publish(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  a public.announcements;
  v_url text;
  v_secret text;
begin
  if not public.app_perm('allow_messages') then
    raise exception 'Brak uprawnień do komunikatów.';
  end if;
  select * into a from public.announcements where id = p_id;
  if not found or not a.push or a.closed_at is not null or a.starts_at > now() + interval '2 minutes' then
    return;                          -- bez push, zakończony albo zaplanowany na później
  end if;

  select value into v_url from public.app_private_settings where key = 'push_function_url';
  select value into v_secret from public.app_private_settings where key = 'push_hook_secret';
  if v_url is null or v_secret is null or v_secret = 'WKLEJ_TUTAJ_HASLO' then
    return;
  end if;
  perform net.http_post(
    url := v_url,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secret', v_secret),
    body := jsonb_build_object('announcement_id', p_id)
  );
end $$;

grant execute on function public.app_announcement_publish(bigint) to authenticated;
revoke execute on function public.app_announcement_publish(bigint) from anon;

commit;

notify pgrst, 'reload schema';

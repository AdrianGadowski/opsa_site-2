-- =====================================================================
-- ZGŁOSZENIA NIEOBECNOŚCI (pracownik zgłasza w portalu, mistrz działu akceptuje)
--
-- absence_requests: pracownik, dział (z chwili zgłoszenia), od–do, powód, opis, status.
--   status: pending (oczekuje) / approved (zaakceptowane) / rejected (odrzucone) / cancelled (anulowane)
--
-- Kto co może:
--   * pracownik - widzi i dodaje tylko swoje zgłoszenia, anuluje tylko oczekujące (app_absence_cancel);
--   * mistrz    - użytkownik z rolą "Mistrz" - widzi i rozpatruje zgłoszenia pracowników
--                 SWOJEGO działu (dział z jego konta w "Użytkownicy") (app_absence_decide);
--   * administrator - widzi i rozpatruje wszystkie.
-- Akceptacja wpisuje dni do harmonogramu (schedule_days) jako zgłoszoną nieobecność z powodem.
--
-- Wymaga wcześniejszego 01_przygotowanie.sql, 02_zabezpieczenie.sql i 26_harmonogram_dni.sql.
-- Można uruchomić ponownie.
-- Uruchom w Supabase: SQL Editor -> wklej całość -> Run.
-- =====================================================================

begin;

-- Czy zalogowany użytkownik jest mistrzem podanego działu (albo administratorem)
create or replace function public.app_is_master_of(p_department bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.app_is_admin() or exists (
    select 1
    from public.users u
    join public.role r on r.id = u.role_id
    where u.auth_id = auth.uid()
      and lower(btrim(r.role)) = 'mistrz'
      and u.department_id is not null
      and u.department_id = p_department
  )
$$;

grant execute on function public.app_is_master_of(bigint) to authenticated;
revoke execute on function public.app_is_master_of(bigint) from anon;

create table if not exists public.absence_requests (
  id            bigint generated by default as identity primary key,
  employee_id   bigint not null references public.employees (id) on delete cascade,
  department_id bigint references public.department (id) on delete set null,
  date_from     date not null,
  date_to       date not null,
  reason        text not null check (reason in ('urlop', 'urlop_na_zadanie', 'l4', 'opieka', 'inny')),
  description   text check (description is null or length(description) <= 200),
  status        text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'cancelled')),
  created_at    timestamptz not null default now(),
  decided_by    bigint references public.users (id) on delete set null,
  decided_at    timestamptz,
  decision_note text check (decision_note is null or length(decision_note) <= 200),
  check (date_to >= date_from),
  check (date_to - date_from <= 60)
);

create index if not exists absence_requests_status_idx on public.absence_requests (status, department_id);
create index if not exists absence_requests_employee_idx on public.absence_requests (employee_id);

alter table public.absence_requests enable row level security;
revoke all on public.absence_requests from anon;
revoke all on public.absence_requests from authenticated;
grant select, insert on public.absence_requests to authenticated;

drop policy if exists absence_requests_select on public.absence_requests;
create policy absence_requests_select on public.absence_requests
  for select to authenticated
  using (employee_id = (select public.app_employee_id())
         or public.app_is_master_of(department_id));

drop policy if exists absence_requests_insert on public.absence_requests;
create policy absence_requests_insert on public.absence_requests
  for insert to authenticated
  with check (employee_id = (select public.app_employee_id()));

-- Przy dodaniu: dział z konta pracownika, status "oczekuje", kontrola dat i nakładania się
create or replace function public.app_trg_absence_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_today date := (now() at time zone 'Europe/Warsaw')::date;
begin
  select e.department_id into new.department_id from public.employees e where e.id = new.employee_id;
  new.status := 'pending';
  new.created_at := now();
  new.decided_by := null;
  new.decided_at := null;
  new.decision_note := null;
  new.description := nullif(btrim(coalesce(new.description, '')), '');

  if new.date_from < v_today - 14 then
    raise exception 'Nieobecność można zgłosić najwyżej 14 dni wstecz.';
  end if;
  if new.reason = 'urlop_na_zadanie' and new.date_from < v_today then
    raise exception 'Urlop na żądanie można zgłosić najpóźniej w dniu nieobecności.';
  end if;
  if exists (
    select 1 from public."Closed_Periods" c
    where c.is_locked
      and c.year_month between to_char(new.date_from, 'YYYY-MM') and to_char(new.date_to, 'YYYY-MM')
  ) then
    raise exception 'Miesiąc w podanym okresie jest zablokowany.';
  end if;
  if exists (
    select 1 from public.absence_requests a
    where a.employee_id = new.employee_id
      and a.status in ('pending', 'approved')
      and a.date_from <= new.date_to and a.date_to >= new.date_from
  ) then
    raise exception 'Masz już zgłoszenie obejmujące część tych dni.';
  end if;
  return new;
end $$;

drop trigger if exists app_absence_insert on public.absence_requests;
create trigger app_absence_insert
  before insert on public.absence_requests
  for each row execute function public.app_trg_absence_insert();

-- Mistrzowie działu zalogowanego pracownika (kto zobaczy zgłoszenie)
create or replace function public.app_absence_approvers()
returns table (name text)
language sql
stable
security definer
set search_path = public
as $$
  select btrim(coalesce(u.name, '') || ' ' || coalesce(u.last_name, ''))
  from public.employees e
  join public.users u on u.department_id = e.department_id
  join public.role r on r.id = u.role_id
  where e.id = public.app_employee_id()
    and e.department_id is not null
    and lower(btrim(r.role)) = 'mistrz'
  order by 1
$$;

grant execute on function public.app_absence_approvers() to authenticated;
revoke execute on function public.app_absence_approvers() from anon;

-- Anulowanie przez pracownika (tylko własne, tylko oczekujące)
create or replace function public.app_absence_cancel(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.absence_requests
  set status = 'cancelled', decided_at = now()
  where id = p_id
    and employee_id = public.app_employee_id()
    and status = 'pending';
  if not found then
    raise exception 'Nie można anulować tego zgłoszenia (już rozpatrzone albo nie Twoje).';
  end if;
end $$;

grant execute on function public.app_absence_cancel(bigint) to authenticated;
revoke execute on function public.app_absence_cancel(bigint) from anon;

-- Akceptacja / odrzucenie przez mistrza działu (albo administratora).
-- Akceptacja wpisuje każdy dzień do harmonogramu jako zgłoszoną nieobecność.
create or replace function public.app_absence_decide(p_id bigint, p_approve boolean, p_note text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.absence_requests;
  v_label text;
begin
  select * into r from public.absence_requests where id = p_id for update;
  if not found then
    raise exception 'Nie znaleziono zgłoszenia.';
  end if;
  if not public.app_is_master_of(r.department_id) then
    raise exception 'Zgłoszenia z tego działu może rozpatrzyć tylko mistrz działu.';
  end if;
  if r.status <> 'pending' then
    raise exception 'To zgłoszenie zostało już rozpatrzone.';
  end if;

  update public.absence_requests
  set status = case when p_approve then 'approved' else 'rejected' end,
      decided_by = public.app_user_id(),
      decided_at = now(),
      decision_note = nullif(btrim(coalesce(p_note, '')), '')
  where id = p_id;

  if p_approve then
    v_label := case r.reason
      when 'urlop' then 'urlop'
      when 'urlop_na_zadanie' then 'urlop na żądanie'
      when 'l4' then 'L4'
      when 'opieka' then 'opieka'
      else coalesce(left(r.description, 60), 'inny')
    end;
    insert into public.schedule_days (employee_id, day, kind, note)
    select r.employee_id, d::date, 'absence', v_label
    from generate_series(r.date_from, r.date_to, interval '1 day') as d
    on conflict (employee_id, day) do update
      set kind = 'absence', note = excluded.note, time_from = null, time_to = null;
  end if;
end $$;

grant execute on function public.app_absence_decide(bigint, boolean, text) to authenticated;
revoke execute on function public.app_absence_decide(bigint, boolean, text) from anon;

commit;

notify pgrst, 'reload schema';

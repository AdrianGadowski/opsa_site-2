-- ---------------------------------------------------------------------
-- 2. Urządzenia z włączonymi powiadomieniami
-- ---------------------------------------------------------------------
create table if not exists public.push_subscriptions (
  id          bigint generated by default as identity primary key,
  user_id     bigint references public.users (id) on delete cascade,
  employee_id bigint references public.employees (id) on delete cascade,
  endpoint    text not null unique,
  p256dh      text not null,
  auth        text not null,
  user_agent  text,
  created_at  timestamptz not null default now(),
  check ((user_id is null) <> (employee_id is null))
);

alter table public.push_subscriptions enable row level security;
revoke all on public.push_subscriptions from anon, authenticated;
grant select on public.push_subscriptions to authenticated;

drop policy if exists push_subscriptions_own on public.push_subscriptions;
create policy push_subscriptions_own on public.push_subscriptions
  for select to authenticated
  using (user_id = (select public.app_user_id()) or employee_id = (select public.app_employee_id()));

-- Zapis urządzenia dla zalogowanej osoby (to samo urządzenie po zmianie konta przechodzi na nowe konto)
create or replace function public.app_push_subscribe(p_endpoint text, p_p256dh text, p_auth text, p_user_agent text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user bigint := public.app_user_id();
  v_emp bigint := public.app_employee_id();
begin
  if v_user is null and v_emp is null then
    raise exception 'Brak zalogowanego konta.';
  end if;
  if coalesce(p_endpoint, '') !~ '^https://' or coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '' then
    raise exception 'Nieprawidłowe dane urządzenia.';
  end if;
  delete from public.push_subscriptions where endpoint = p_endpoint;
  insert into public.push_subscriptions (user_id, employee_id, endpoint, p256dh, auth, user_agent)
  values (v_user, case when v_user is null then v_emp end, p_endpoint, p_p256dh, p_auth, left(p_user_agent, 300));
end $$;

create or replace function public.app_push_unsubscribe(p_endpoint text)
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.push_subscriptions
  where endpoint = p_endpoint
    and (user_id = public.app_user_id() or employee_id = public.app_employee_id());
$$;

grant execute on function public.app_push_subscribe(text, text, text, text) to authenticated;
grant execute on function public.app_push_unsubscribe(text) to authenticated;
revoke execute on function public.app_push_subscribe(text, text, text, text) from anon;
revoke execute on function public.app_push_unsubscribe(text) from anon;

-- ---------------------------------------------------------------------
-- 3. Wywołanie funkcji po zmianie zgłoszenia nieobecności
-- ---------------------------------------------------------------------
create or replace function public.app_trg_absence_push()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event text;
  v_url text;
  v_secret text;
begin
  if tg_op = 'INSERT' then
    v_event := 'new';
  elsif new.status is distinct from old.status then
    v_event := case new.status
      when 'approved' then 'approved'
      when 'rejected' then 'rejected'
      when 'cancelled' then 'cancelled'
    end;
  end if;
  if v_event is null then
    return new;
  end if;

  select value into v_url from public.app_private_settings where key = 'push_function_url';
  select value into v_secret from public.app_private_settings where key = 'push_hook_secret';
  if v_url is null or v_secret is null or v_secret = 'BFZWApHRRyph6cF-_UWMITsQ05rgQ-y-' then
    return new;                      -- powiadomienia nieskonfigurowane: zgłoszenie działa normalnie
  end if;

  begin
    perform net.http_post(
      url := v_url,
      headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secret', v_secret),
      body := jsonb_build_object('request_id', new.id, 'event', v_event)
    );
  exception when others then
    raise warning 'Powiadomienie push nie zostało wysłane: %', sqlerrm;
  end;
  return new;
end $$;

drop trigger if exists app_absence_push on public.absence_requests;
create trigger app_absence_push
  after insert or update of status on public.absence_requests
  for each row execute function public.app_trg_absence_push();

commit;


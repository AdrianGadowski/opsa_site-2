-- POWIADOMIENIA PUSH O ZGŁOSZENIACH NIEOBECNOŚCI
--
--  * push_subscriptions - urządzenia, które włączyły powiadomienia (użytkownik albo pracownik);
--    każdy widzi i usuwa tylko swoje; zapis przez app_push_subscribe / app_push_unsubscribe.
--  * Po dodaniu zgłoszenia, jego rozpatrzeniu albo anulowaniu baza wywołuje funkcję
--    Edge Function "absence-push" (rozszerzenie pg_net), która wysyła powiadomienia:
--      nowe / anulowane zgłoszenie -> mistrzowie działu pracownika (brak mistrza -> administratorzy),
--      akceptacja / odrzucenie      -> pracownik.
--
-- PRZED URUCHOMIENIEM: w linii z 'WKLEJ_TUTAJ_HASLO' wpisz hasło wywołania funkcji
-- (to samo, co w sekrecie PUSH_HOOK_SECRET funkcji; generator: tools/vapid.html).
--
-- Wymaga wcześniejszego 27_zgloszenia_nieobecnosci.sql. Można uruchomić ponownie.
-- Uruchom w Supabase: SQL Editor -> wklej całość -> Run.
-- =====================================================================


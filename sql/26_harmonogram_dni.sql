-- =====================================================================
-- HARMONOGRAM DZIEŃ PO DNIU
--
-- schedule_days: jeden wpis na pracownika i dzień
--   kind = 'work'    - praca w godzinach time_from–time_to ("06:30" itd.)
--   kind = 'off'     - wolne
--   kind = 'absence' - zgłoszona nieobecność (note: powód, np. urlop, L4)
-- Brak wpisu = nic nie zaplanowano.
--
-- Odczyt: każdy użytkownik systemu (lista pracowników, Obecność) oraz pracownik - tylko swoje dni.
-- Zmiany: wyłącznie użytkownicy z uprawnieniem "Harmonogram" (allow_schedule).
--
-- Skrypt przenosi też dotychczasowe godziny tygodniowe (kolumny week_1..week_53 w employees,
-- bieżący rok) jako dni pn–pt. Istniejących wpisów dziennych nie nadpisuje.
-- Kolumny week_N zostają w bazie (nieużywane), można je usunąć później.
--
-- Wymaga wcześniejszego 01_przygotowanie.sql i 04_harmonogram.sql. Można uruchomić ponownie.
-- Uruchom w Supabase: SQL Editor -> wklej całość -> Run.
-- =====================================================================

begin;

create table if not exists public.schedule_days (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  day         date not null,
  kind        text not null check (kind in ('work', 'off', 'absence')),
  time_from   text check (time_from ~ '^\d{2}:\d{2}$'),
  time_to     text check (time_to ~ '^\d{2}:\d{2}$'),
  note        text check (note is null or length(note) <= 80),
  updated_at  timestamptz not null default now(),
  updated_by  bigint default public.app_user_id(),
  unique (employee_id, day),
  check (kind <> 'work' or (time_from is not null and time_to is not null and time_from <> time_to))
);

create index if not exists schedule_days_day_idx on public.schedule_days (day);

alter table public.schedule_days enable row level security;
revoke all on public.schedule_days from anon;
grant select, insert, update, delete on public.schedule_days to authenticated;

drop policy if exists schedule_days_select on public.schedule_days;
create policy schedule_days_select on public.schedule_days
  for select to authenticated
  using ((select public.app_user_id()) is not null
         or employee_id = (select public.app_employee_id()));

drop policy if exists schedule_days_write on public.schedule_days;
create policy schedule_days_write on public.schedule_days
  for all to authenticated
  using ((select public.app_perm('allow_schedule')))
  with check ((select public.app_perm('allow_schedule')));

-- kto i kiedy zmienił wpis
create or replace function public.app_trg_schedule_days_stamp()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();
  new.updated_by := coalesce(public.app_user_id(), new.updated_by);
  if new.kind <> 'work' then
    new.time_from := null;
    new.time_to := null;
  end if;
  if new.kind <> 'absence' then
    new.note := null;
  end if;
  return new;
end $$;

drop trigger if exists app_schedule_days_stamp on public.schedule_days;
create trigger app_schedule_days_stamp
  before insert or update on public.schedule_days
  for each row execute function public.app_trg_schedule_days_stamp();

-- ---------------------------------------------------------------------
-- Przeniesienie godzin tygodniowych (week_N, bieżący rok) na dni pn–pt.
-- Numer tygodnia jak w aplikacji: tydzień 1 zaczyna się 1 stycznia, kolejne w poniedziałki.
-- ---------------------------------------------------------------------
with yr as (
  select extract(year from (now() at time zone 'Europe/Warsaw'))::int as y
), days as (
  select d::date as day,
         floor((extract(doy from d) - 1 + (extract(isodow from make_date(yr.y, 1, 1)) - 1)) / 7)::int + 1 as week
  from yr, generate_series(make_date(yr.y, 1, 1), make_date(yr.y, 12, 31), interval '1 day') as d
  where extract(isodow from d) between 1 and 5
), src as (
  select e.id as employee_id, days.day,
         regexp_match(to_jsonb(e) ->> ('week_' || days.week), '(\d{1,2})[:.](\d{2})\D+(\d{1,2})[:.](\d{2})') as m
  from public.employees e
  cross join days
)
insert into public.schedule_days (employee_id, day, kind, time_from, time_to)
select employee_id, day, 'work',
       lpad(m[1], 2, '0') || ':' || m[2],
       lpad(m[3], 2, '0') || ':' || m[4]
from src
where m is not null
  and lpad(m[1], 2, '0') || ':' || m[2] <> lpad(m[3], 2, '0') || ':' || m[4]
on conflict do nothing;

commit;

notify pgrst, 'reload schema';
